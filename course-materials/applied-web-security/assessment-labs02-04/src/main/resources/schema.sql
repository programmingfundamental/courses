CREATE TABLE IF NOT EXISTS workspaces (
  id VARCHAR(64) PRIMARY KEY, created VARCHAR(40) NOT NULL,
  participant VARCHAR(120) NOT NULL DEFAULT '', answers CLOB NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS lab_runs (
  workspace VARCHAR(64), case_no INT, generation INT NOT NULL DEFAULT 1,
  PRIMARY KEY(workspace, case_no)
);
CREATE TABLE IF NOT EXISTS lab_users (
  workspace VARCHAR(64), case_no INT, username VARCHAR(32), password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(10) NOT NULL, PRIMARY KEY(workspace, case_no, username)
);
CREATE TABLE IF NOT EXISTS tasks (
  workspace VARCHAR(64), case_no INT, id INT, summary VARCHAR(160) NOT NULL,
  description VARCHAR(2000) NOT NULL, owner VARCHAR(32) NOT NULL,
  PRIMARY KEY(workspace, case_no, id)
);
CREATE TABLE IF NOT EXISTS reports (
  workspace VARCHAR(64), case_no INT, id INT, task_id INT NOT NULL, report_text VARCHAR(2000) NOT NULL,
  PRIMARY KEY(workspace, case_no, id)
);
CREATE TABLE IF NOT EXISTS lab_sessions (
  id VARCHAR(64) PRIMARY KEY, workspace VARCHAR(64) NOT NULL, case_no INT NOT NULL,
  username VARCHAR(32), expires BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS session_scope ON lab_sessions(workspace, case_no);
CREATE TABLE IF NOT EXISTS lab_tokens (
  id VARCHAR(64) PRIMARY KEY, workspace VARCHAR(64) NOT NULL, case_no INT NOT NULL,
  username VARCHAR(32) NOT NULL, session_id VARCHAR(64) NOT NULL, kind VARCHAR(20) NOT NULL, expires BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS evidence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace VARCHAR(64) NOT NULL, case_no INT NOT NULL, generation INT NOT NULL, record_json CLOB NOT NULL
);
CREATE INDEX IF NOT EXISTS evidence_scope ON evidence(workspace, id);
